/* ── Saved Systems List ── */
export function SizedSystemsList({ onOpen }: { onOpen: (q: SavedQuote) => void }) {
  const [quotes, setQuotes] = useState<SavedQuote[]>(() =>
    loadSavedQuotes().filter((q) => q.source === 'maker' && q.sizing),
  );

  function remove(id: string) {
    deleteQuote(id);
    setQuotes(loadSavedQuotes().filter((q) => q.source === 'maker' && q.sizing));
  }

  if (quotes.length === 0) {
    return (
      <div className="pt-empty">
        <span className="pt-empty-icon">⚡</span>
        <p>No sized systems yet</p>
        <span>Use "Size a System" to calculate and save your system sizing.</span>
      </div>
    );
  }

  return (
    <div>
      <div
        className="pt-row pt-row-head"
        style={{ gridTemplateColumns: '1fr 90px 110px 90px 90px 220px 80px 60px 50px' }}
      >
        <span>Client / Location</span>
        <span>Type</span>
        <span>Array</span>
        <span>Inverter</span>
        <span>Battery</span>
        <span>Ref Number</span>
        <span>Date / remaining</span>
        <span style={{ justifyContent: 'center' }}>Open</span>
        <span style={{ justifyContent: 'center' }}>Del</span>
      </div>

      {quotes.map((q) => {
        const s = q.sizing!;
        const created = new Date(q.created_at);
        const expiry = new Date(created.getTime() + 30 * 24 * 60 * 60 * 1000);
        const daysLeft = Math.ceil((expiry.getTime() - Date.now()) / (1000 * 60 * 60 * 24));
        const expired = daysLeft <= 0;
        return (
          <div
            key={q.id}
            className="pt-row"
            style={{
              gridTemplateColumns: '1fr 90px 110px 90px 90px 220px 80px 60px 50px',
              cursor: 'pointer',
            }}
            onClick={() => onOpen(q)}
          >
            <span style={{ flexDirection: 'column', alignItems: 'flex-start', gap: 2 }}>
              <span style={{ fontSize: 12, fontWeight: 700, color: '#1d2f25' }}>{q.name || 'Unknown'}</span>
              <span style={{ fontSize: 11, color: '#69736d' }}>{q.district ?? '—'}</span>
            </span>
            <span>
              <span className="pt-status pt-status-blue">{(q.system_type ?? '').replace('_', '-')}</span>
            </span>
            <span style={{ fontSize: 12 }}>
              {s.arrayKwp} kWp · {s.panels} panels
            </span>
            <span style={{ fontSize: 12 }}>{s.inverterKw} kW</span>
            <span style={{ fontSize: 12 }}>
              {s.batteryKwh > 0 ? `${s.batteryKwh} kWh` : <span style={{ color: '#9ba19d' }}>None</span>}
            </span>
            <span style={{ fontSize: 10, fontWeight: 700, color: '#1d2f25', whiteSpace: 'nowrap' }}>
              {q.ref.startsWith('TCOIN-')
                ? q.ref
                : (() => {
                    const d = new Date(q.created_at);
                    const MONTHS = [
                      'Jan',
                      'Feb',
                      'Mar',
                      'Apr',
                      'May',
                      'Jun',
                      'Jul',
                      'Aug',
                      'Sep',
                      'Oct',
                      'Nov',
                      'Dec',
                    ];
                    const day = String(d.getDate()).padStart(2, '0');
                    const seq = q.ref.replace(/\D/g, '').slice(-3).padStart(3, '0');
                    return `TCOIN-SLA-EST${seq}\u2013${day}${MONTHS[d.getMonth()]}${d.getFullYear()}`;
                  })()}
            </span>
            <span style={{ flexDirection: 'column', alignItems: 'flex-start', gap: 2 }}>
              <span style={{ fontSize: 10, color: '#69736d' }}>
                {created.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })}
              </span>
              <span
                style={{
                  fontSize: 10,
                  fontWeight: 700,
                  color: expired ? '#d92c32' : daysLeft <= 7 ? '#F5A623' : '#14723a',
                }}
              >
                {expired ? 'Expired' : `${daysLeft}d left`}
              </span>
            </span>
            <span
              style={{ justifyContent: 'center' }}
              onClick={(e) => {
                e.stopPropagation();
                onOpen(q);
              }}
            >
              <button
                type="button"
                style={{
                  background: '#14723a',
                  border: 'none',
                  cursor: 'pointer',
                  color: '#fff',
                  fontSize: 11,
                  fontWeight: 700,
                  padding: '3px 10px',
                  borderRadius: 4,
                }}
              >
                Open
              </button>
            </span>
            <span style={{ justifyContent: 'center' }} onClick={(e) => e.stopPropagation()}>
              <button
                type="button"
                onClick={() => remove(q.id)}
                style={{
                  background: 'none',
                  border: 'none',
                  cursor: 'pointer',
                  color: '#d92c32',
                  fontSize: 16,
                  lineHeight: 1,
                }}
              >
                ×
              </button>
            </span>
          </div>
        );
      })}
    </div>
  );
}
